"""Write the supplementary tables from the archived case-level results."""

import argparse
import json
from math import log2
from pathlib import Path
from statistics import mean, median


PROBES = ("0.75", "1.25", "1.75")
WIDTH_MODELS = ("measured", "periodic_anchor", "isolated_anchor")
CONDITIONS = (
    ("nominal", "Nominal"),
    ("variable_probe", "Variable probe"),
    ("variable_probe_and_landscape", "Variable probe and energy shape"),
)


def load(evidence, name):
    return json.loads((evidence / (name + ".json")).read_text())


def width_gap(chord, probe, model):
    first, second = chord["widths_nm"][probe][model]
    return first - second


def mos2_tables(evidence, output):
    records = load(evidence, "moire_wall_energy_readout_v01")
    scans = sorted(records["scans"].items(), key=lambda item: item[1]["twist_deg"])
    score_rows, settings_rows = [], []
    for name, scan in scans:
        widths = scan["chords"]
        if len(widths) != scan["qualified_wall_count"]:
            raise ValueError(f"{name}: mismatched qualified count")
        gaps = [round(mean(width_gap(chord, "1.25", model) for chord in widths), 2) + 0.
                for model in WIDTH_MODELS]
        row_spacing = median(chord["spacing_nm"] for chord in widths)
        ratio = scan["typical_barrier_ratio"]["1.25"]["measured"]
        score_rows.append(
            f"{name} & {scan['twist_deg']:.3f} & {len(widths)}/{scan['total_wall_candidates']} "
            f"& {row_spacing:.2f} & {gaps[0]:.2f} & {gaps[1]:.2f} & {gaps[2]:.2f} & {ratio:.2f}"
        )
    for probe in PROBES:
        high = [scan for _, scan in scans if scan["twist_deg"] >= 1.0]
        gap_errors = {model: [] for model in WIDTH_MODELS[1:]}
        ratio_errors = {model: [] for model in WIDTH_MODELS[1:]}
        for scan in high:
            gap = {model: mean(width_gap(chord, probe, model) for chord in scan["chords"])
                   for model in WIDTH_MODELS}
            ratio = scan["typical_barrier_ratio"][probe]
            for model in WIDTH_MODELS[1:]:
                gap_errors[model].append(abs(gap[model] - gap["measured"]))
                ratio_errors[model].append(abs(log2(ratio[model] / ratio["measured"])))
        wins = sum(periodic < isolated for periodic, isolated in zip(*gap_errors.values(), strict=True))
        settings_rows.append(f"{probe} & {mean(gap_errors['periodic_anchor']):.3f} "
                             f"& {mean(gap_errors['isolated_anchor']):.3f} "
                             f"& {mean(ratio_errors['periodic_anchor']):.3f} "
                             f"& {mean(ratio_errors['isolated_anchor']):.3f} & {wins}/{len(high)}")
    write_rows(output / "mos2_map_scores.tex", "MoSMapRows", score_rows)
    write_rows(output / "mos2_probe_sensitivity.tex", "MoSProbeRows", settings_rows)
    print(f"MoS2: {sum(len(s['chords']) for _, s in scans)} qualified sections in {len(scans)} maps")


def recovery_table(evidence, output):
    records = load(evidence, "mos2_barrier_recovery_v01")
    rows = []
    for angle, spacing in (("0.55", 28.6), ("1.85", 8.5)):
        for condition, label in CONDITIONS:
            summary = records["summary"][f"{angle}/{condition}"]
            isolated = summary["isolated/both/profile_shapes"]
            periodic = summary["periodic/both/profile_shapes"]
            total = periodic["realizations"]
            count = round(total * periodic["fraction_within_20_percent"])
            rows.append(f"{spacing:.1f} & {label} & {100*isolated['median_absolute_relative_error']:.1f} "
                        f"& {100*periodic['median_absolute_relative_error']:.1f} & {count}/{total} "
                        f"& {100*periodic['median_noise_interval_width_over_truth']:.1f}")
    write_rows(output / "synthetic_recovery.tex", "RecoveryRows", rows)


def write_rows(path, name, rows):
    header = f"% Generated by build_tables.py\n\\newcommand{{\\{name}}}{{%\n"
    path.write_text(header + "\n".join(row + r" \\" for row in rows) + "\n}\n")


def main():
    directory = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--evidence", type=Path, default=directory.parents[1] / "evidence")
    parser.add_argument("--output", type=Path, default=directory)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    mos2_tables(args.evidence, args.output)
    recovery_table(args.evidence, args.output)


if __name__ == "__main__":
    main()
