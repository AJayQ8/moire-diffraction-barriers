    out = [
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{\textbf{Width differences on sections included at all three fitting windows.} Each cell is the mean signed gap $w_1-w_2$ in nm for the measured profile or the published reference relaxation. The same 175 original sections qualify in both diffraction orders for the measured profiles and all four relaxed candidates at each of the adaptive, $4.25\nm$ and $2.50\nm$ windows. All values use the original three-shell intensity fit and nominal $1.25\nm$ probe.}",
        r"\label{tab:common-windows}",
        r"\begin{tabular}{@{}lrr rr rr rr@{}}",
        r"\toprule",
        r"& & & \multicolumn{2}{c}{Adaptive} & \multicolumn{2}{c}{$4.25\nm$} & \multicolumn{2}{c}{$2.50\nm$} \\",
        r"\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}",
        r"Map & Twist ($^\circ$) & $n$ & Measured & Reference & Measured & Reference & Measured & Reference \\",
        r"\midrule",
    ]
