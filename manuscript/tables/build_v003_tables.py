def short_window_tables(primary: dict, uncertainty: dict) -> str:
    scans = primary["scans"]
    screen = []
    first_means = []
    for scan_name, scan in scans.items():
        for wall in scan["walls"]:
            if not wall.get("original_cohort"):
                continue
            observed = wall["readouts"]["compact"][PROBE]["2.50"]["measured"]
            core = finite(wall.get("model_core_widths_nm", {}).get("anchor"))
            probe_rows = [wall.get("short_window_anchor_read_as_1.25_nm", {}).get(p, {}) for p in ("0.75", "1.25", "1.75")]
            probes_good = all(all(qual_pair(row.get("qualified"))) for row in probe_rows)
            if qual_pair(observed.get("qualified"))[0] and core is not None and probes_good:
                synth = [pair(row.get("widths_nm"))[0] for row in probe_rows]
                if all(x is not None for x in synth):
                    screen.append((core, synth))
        observed_widths = []
        for wall in scan["walls"]:
            if not wall.get("original_cohort"):
                continue
            fit = wall["readouts"]["compact"][PROBE]["2.50"]["measured"]
            if qual_pair(fit.get("qualified"))[0]:
                observed_widths.append(pair(fit.get("widths_nm"))[0])
        first_means.append((scan_name, scan["inferred_twist_deg"], len(observed_widths),
                            mean(observed_widths) if observed_widths else None))
    if len(screen) != 183:
        raise ValueError(f"Expected 183 sections in the short-window screen, found {len(screen)}")
    probe_labels = ("0.75", "1.25", "1.75")
    s = uncertainty["short_window_response"]["synthetic_anchor_render"]
    if (s["observer_window_half_width_nm"] != 2.5
            or s["observer_probe_fwhm_nm"] != 1.25
            or s["true_rendered_probe_fwhm_nm"]["1.25"]["paired_intrinsic_width_walls"] != 243):
        raise ValueError("Short-window sensitivity summary does not match the saved protocol")
    table1 = [
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{\textbf{Short-window test using simulated profiles without noise.} We fit the simulated profile for the published energy with a $2.50\nm$ half-window and a fixed $1.25\nm$ probe. We retain sections from the original comparison with a qualifying measured first-order fit, a finite intrinsic core width and qualifying fits to simulated profiles in both diffraction orders at all three true probe sizes ($n=183$). Error is median absolute deviation from the intrinsic midpoint slip-gradient width. Bias is the median difference from the correctly specified $1.25\nm$ probe fit. The calculation isolates probe/window response in a known synthetic displacement field.}",
        r"\label{tab:short-window-screen}",
        r"\begin{tabular}{@{}rrrr@{}}",
        r"\toprule",
        r"True probe FWHM (nm) & Sections & Median absolute error (nm) & Median bias vs $1.25\nm$ (nm) \\",
        r"\midrule",
    ]
    nominal = [row[1][1] for row in screen]
    for i, probe in enumerate(probe_labels):
        err = median(abs(row[1][i] - row[0]) for row in screen)
        bias = median(row[1][i] - nominal[j] for j, row in enumerate(screen))
        table1.append(f"{probe} & {len(screen)} & {err:.3f} & {bias:.3f}" + r" \\")
    table1.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    table2 = [
        r"\begin{table}[H]",
        r"\centering",
        r"\small",
        r"\caption{\textbf{Measured first-order widths in the $2.50\nm$ window.} Values are map means of qualified measured first-order fits at nominal $1.25\nm$ probe. The listed $n$ is the number of qualified sections in each map. These values summarize the measured diffraction profiles; intrinsic slip-gradient widths are reported for the model fields.}",
        r"\label{tab:short-window-real}",
        r"\begin{tabular}{@{}lrrr@{}}",
        r"\toprule",
        r"Map & Twist ($^\circ$) & $n$ & Mean $w_1$ (nm) \\",
        r"\midrule",
    ]
    for scan_name, twist, n, width in sorted(first_means, key=lambda row: row[1]):
        table2.append(f"{scan_name} & {twist:.3f} & {n} & {fmt_num(width, 3)}" + r" \\")
    table2.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    return "\n".join(table1 + table2)


