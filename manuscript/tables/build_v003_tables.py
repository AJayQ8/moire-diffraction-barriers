def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_json(directory: Path, name: str) -> tuple[dict, Path]:
    path = directory / name
    return json.loads(path.read_text()), path


def finite(value):
    try:
        value = float(value)
    except (TypeError, ValueError):
        return None
    return value if math.isfinite(value) else None


def pair(value):
    if not isinstance(value, list) or len(value) != 2:
        return (None, None)
    return tuple(finite(x) for x in value)


def qual_pair(value):
    if not isinstance(value, list) or len(value) != 2:
        return (False, False)
    return tuple(value[i] is True for i in range(2))


def index_control_walls(controls: dict) -> None:
    for scan in controls["scans"].values():
        scan["_wall_index"] = {tuple(wall["centers"]): wall for wall in scan["walls"]}


def paired_width_cohort(walls: list[dict], get_readout) -> list[dict]:
    """Measured plus four relaxed fields must qualify in both diffraction orders."""
    selected = []
    for wall in walls:
        if not wall.get("original_cohort"):
            continue
        ro = get_readout(wall)
        fits = {"measured": ro.get("measured", {})}
        fits.update(ro.get("models", {}))
        if all(
            all(qual_pair(fits[name].get("qualified")))
            for name in ("measured", *RELAXED)
        ):
            selected.append(wall)
    return selected


def rigid_width_cohort(common: list[dict], get_readout) -> list[dict]:
    return [
        wall for wall in common
        if all(qual_pair(get_readout(wall).get("models", {}).get("rigid", {}).get("qualified")))
    ]


def mean_width_pair(walls: list[dict], get_readout, model: str) -> tuple[float | None, float | None]:
    if not walls:
        return (None, None)
    vals = []
    for wall in walls:
        ro = get_readout(wall)
        fit = ro["measured"] if model == "measured" else ro.get("models", {}).get(model, {})
        vals.append(pair(fit.get("widths_nm")))
    return tuple(mean(v[i] for v in vals if v[i] is not None) if any(v[i] is not None for v in vals) else None
                 for i in range(2))


def fmt_num(value, digits=2) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def fmt_pair(values) -> str:
    if values is None:
        return "--"
    a, b = values
    return "--" if a is None or b is None else f"{a:.2f}/{b:.2f}"


def fmt_gap(walls: list[dict], get_readout, model: str) -> float | None:
    vals = []
    for wall in walls:
        ro = get_readout(wall)
        fit = ro["measured"] if model == "measured" else ro.get("models", {}).get(model, {})
        w = pair(fit.get("widths_nm"))
        if w[0] is not None and w[1] is not None:
            vals.append(w[0] - w[1])
    return mean(vals) if vals else None


def tex_provenance(input_paths: list[Path], generator_name: str) -> str:
    lines = [f"% Generated by {generator_name}; evidence SHA-256:"]
    for path in input_paths:
        lines.append(f"% {path.name} {digest(path)}")
    return "\n".join(lines) + "\n"


