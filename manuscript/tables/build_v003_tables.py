def per_map_width_score(scans: dict, controls: dict, camera: str, window: str, model: str):
    map_errors = {}
    map_anchor_errors = {}
    n_width = 0
    for scan_name, scan in scans.items():
        if camera == "compact":
            walls = scan["walls"]
            get_ro = lambda wall, sn=scan_name, w=window: wall["readouts"]["compact"][PROBE][w]
        else:
            c_by_center = controls["scans"][scan_name]["_wall_index"]
            walls = scan["walls"]
            get_ro = lambda wall, idx=c_by_center, cam=camera, w=window: idx[tuple(wall["centers"])]["readouts"][cam][PROBE][w]
        common = paired_width_cohort(walls, get_ro)
        selected = rigid_width_cohort(common, get_ro) if model == "rigid" else common
        if not selected:
            continue
        n_width += len(selected)
        measured = mean_width_pair(selected, get_ro, "measured")
        candidate = mean_width_pair(selected, get_ro, model)
        anchor = mean_width_pair(selected, get_ro, "anchor")
        if any(x is None for x in (*measured, *candidate, *anchor)):
            continue
        map_errors[scan_name] = (abs(candidate[0] - measured[0]) + abs(candidate[1] - measured[1])) / 2
        map_anchor_errors[scan_name] = (abs(anchor[0] - measured[0]) + abs(anchor[1] - measured[1])) / 2
    mae = mean(map_errors.values()) if map_errors else None
    wins = sum(map_errors[s] < map_anchor_errors[s] for s in map_errors if s in map_anchor_errors) if model != "anchor" else None
    return mae, n_width, len(map_errors), wins, map_errors


def per_map_shape_score(scans: dict, controls: dict, camera: str, window: str, model: str):
    map_scores = {}
    map_anchor = {}
    n_scores = 0
    for scan_name, scan in scans.items():
        if camera == "compact":
            walls = scan["walls"]
            get_ro = lambda wall, w=window: wall["readouts"]["compact"][PROBE][w]
        else:
            c_by_center = controls["scans"][scan_name]["_wall_index"]
            walls = scan["walls"]
            get_ro = lambda wall, idx=c_by_center, cam=camera, w=window: idx[tuple(wall["centers"])]["readouts"][cam][PROBE][w]
        candidate_vals, anchor_vals = [], []
        for wall in walls:
            if not wall.get("original_cohort"):
                continue
            ro = get_ro(wall)
            c = pair(ro.get("models", {}).get(model, {}).get("transfer_error"))
            a = pair(ro.get("models", {}).get("anchor", {}).get("transfer_error"))
            if any(x is None for x in c) or any(x is None for x in a):
                continue
            candidate_vals.append(mean(c))
            anchor_vals.append(mean(a))
        if candidate_vals:
            map_scores[scan_name] = mean(candidate_vals)
            map_anchor[scan_name] = mean(anchor_vals)
            n_scores += len(candidate_vals)
    score = mean(map_scores.values()) if map_scores else None
    wins = sum(map_scores[s] < map_anchor[s] for s in map_scores) if model != "anchor" else None
    return score, n_scores, len(map_scores), wins, map_scores


